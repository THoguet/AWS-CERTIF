import boto3  # noqa: E402
import pytest  # noqa: E402


def _items(n):
    return [{"pk": {"S": f"item-{i:03d}"}, "value": {"N": str(i)}} for i in range(n)]


class ThrottlingClient:
    """Fake client: the first `throttle_calls` calls leave the last 3 requests unprocessed."""

    def __init__(self, throttle_calls):
        self.throttle_calls, self.calls, self.written = throttle_calls, 0, []

    def batch_write_item(self, RequestItems):
        self.calls += 1
        (table, requests), = RequestItems.items()
        assert len(requests) <= 25, "BatchWriteItem accepts at most 25 requests"
        if self.calls <= self.throttle_calls and len(requests) > 3:
            self.written.extend(r["PutRequest"]["Item"] for r in requests[:-3])
            return {"UnprocessedItems": {table: requests[-3:]}}
        if self.calls <= self.throttle_calls:
            return {"UnprocessedItems": {table: requests}}
        self.written.extend(r["PutRequest"]["Item"] for r in requests)
        return {"UnprocessedItems": {}}


def test_writes_everything_with_moto(aws):
    client = boto3.client("dynamodb")
    client.create_table(
        TableName="Events",
        BillingMode="PAY_PER_REQUEST",
        AttributeDefinitions=[{"AttributeName": "pk", "AttributeType": "S"}],
        KeySchema=[{"AttributeName": "pk", "KeyType": "HASH"}],
    )
    batch_put(client, "Events", _items(60), sleep=lambda s: None)
    assert client.scan(TableName="Events", Select="COUNT")["Count"] == 60


def test_retries_unprocessed_items_with_backoff():
    client, sleeps = ThrottlingClient(throttle_calls=2), []
    batch_put(client, "Events", _items(10), sleep=sleeps.append)
    assert len(client.written) == 10
    assert sleeps == pytest.approx([0.05, 0.1])


def test_gives_up_eventually():
    client = ThrottlingClient(throttle_calls=100)
    with pytest.raises(RuntimeError):
        batch_put(client, "Events", _items(5), sleep=lambda s: None, max_retries=3)
    assert client.calls == 4
