import time

BATCH_SIZE = 25
BASE_DELAY = 0.05


def chunks(items: list, size: int = BATCH_SIZE):
    for start in range(0, len(items), size):
        yield items[start : start + size]


def batch_put(client, table_name: str, items: list[dict], sleep=time.sleep, max_retries: int = 5) -> None:
    request = {table_name: [{"PutRequest": {"Item": item}} for item in items]}  # TODO: max 25 per call
    client.batch_write_item(RequestItems=request)  # TODO: what about UnprocessedItems?


